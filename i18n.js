// 文字を取り出す。{q} などは vars の値に置き換える。ない言語は英語、それもなければ日本語
function tr(lang, key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? STR.ja[key] ?? key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

// data-i18n（中身）・data-i18n-title（説明）・data-i18n-ph（入力欄の薄い文字）を付けたところを、その言語にする
function applyI18n(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = tr(lang, el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = tr(lang, el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = tr(lang, el.dataset.i18nPh); });
  document.documentElement.lang = lang;
}

